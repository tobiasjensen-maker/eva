import { createContext, useContext } from 'react';

// Lightweight demo i18n: t() looks the English string up in the Danish dictionary
// and falls back to the English original, so untranslated strings degrade gracefully.
export type Lang = 'en' | 'da';

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (s: string) => string }>({
    lang: 'en',
    setLang: () => {},
    t: (s) => s,
});

export const useLang = () => useContext(LangContext);

export function translate(lang: Lang, s: string): string {
    if (lang !== 'da') return s;
    const hit = DA[s] ?? fromPattern(s);
    // Dev only: record strings shown in Danish mode without a translation (window.__missingDA).
    if (hit === undefined && import.meta.env.DEV && /[a-z]{3}/i.test(s)) ((window as unknown as { __missingDA?: Set<string> }).__missingDA ??= new Set()).add(s);
    return hit ?? s;
}

// Sentences built from data ("In 3 days", "EVA drafted “VAT return — Q1” — …"): translate the frame,
// and translate each captured part on its own.
const MONTHS_DA: Record<string, string> = { Jan: 'jan.', Feb: 'feb.', Mar: 'mar.', Apr: 'apr.', May: 'maj', Jun: 'jun.', Jul: 'jul.', Aug: 'aug.', Sep: 'sep.', Oct: 'okt.', Nov: 'nov.', Dec: 'dec.' };
const PATTERNS: [RegExp, (m: string[], tr: (x: string) => string) => string][] = [
    [/^Overdue (\d+) days?$/, (m) => `${m[1]} ${m[1] === '1' ? 'dag' : 'dage'} for sent`],
    [/^In (\d+) days?$/, (m) => `Om ${m[1]} ${m[1] === '1' ? 'dag' : 'dage'}`],
    [/^(\d+) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)$/, (m) => `${m[1]}. ${MONTHS_DA[m[2]]}`],
    [/^(\d+) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) at (\d\d:\d\d)$/, (m) => `${m[1]}. ${MONTHS_DA[m[2]]} kl. ${m[3]}`],
    [/^Done (\d+) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)$/, (m) => `Udført ${m[1]}. ${MONTHS_DA[m[2]]}`],
    [/^(\d+) employees$/, (m) => `${m[1]} ansatte`],
    [/^(\d+) (day|week|month)s? ago$/, (m) => `${m[1]} ${{ day: m[1] === '1' ? 'dag' : 'dage', week: m[1] === '1' ? 'uge' : 'uger', month: m[1] === '1' ? 'måned' : 'måneder' }[m[2] as 'day']} siden`],
    [/^EVA drafted a reply to (.+) — (.+)$/, (m, tr) => `EVA har skrevet et svar til ${m[1]} — ${tr(m[2])}`],
    [/^(.+) is waiting for your reply — (.+)$/, (m, tr) => `${m[1]} venter på dit svar — ${tr(m[2])}`],
    [/^EVA drafted “(.+)” — ready for your review$/, (m, tr) => `EVA har lavet et udkast til “${tr(m[1])}” — klar til din gennemgang`],
    [/^You marked “(.+)” done$/, (m, tr) => `Du markerede “${tr(m[1])}” som udført`],
    [/^You reopened “(.+)”$/, (m, tr) => `Du genåbnede “${tr(m[1])}”`],
    [/^You handed “(.+)” to EVA$/, (m, tr) => `Du gav “${tr(m[1])}” til EVA`],
    [/^You took “(.+)” back from EVA$/, (m, tr) => `Du tog “${tr(m[1])}” tilbage fra EVA`],
    [/^You applied EVA’s correction to “(.+)”( \(with your changes\))?$/, (m, tr) => `Du anvendte EVAs rettelse på “${tr(m[1])}”${m[2] ? ' (med dine ændringer)' : ''}`],
    [/^You dismissed EVA’s flag on “(.+)”$/, (m, tr) => `Du afviste EVAs markering af “${tr(m[1])}”`],
    [/^You reviewed EVA’s draft of “(.+)” — (.+)$/, (m, tr) => `Du gennemgik EVAs udkast til “${tr(m[1])}” — ${tr(m[2])}`],
    [/^You replied to (.+) — (.+)$/, (m, tr) => `Du svarede ${m[1]} — ${tr(m[2])}`],
    [/^You closed “(.+)”$/, (m, tr) => `Du lukkede “${tr(m[1])}”`],
    [/^You chose “(.+)”$/, (m, tr) => `Du valgte “${tr(m[1])}”`],
    [/^You chose “(.+)” — logged in Activity\.$/, (m, tr) => `Du valgte “${tr(m[1])}” — logget i Aktivitet.`],
    [/^Built with (.+)’s goals · shareable$/, (m) => `Bygget med ${m[1]}s mål · kan deles`],
    [/^Revenue (up|down) (\d+)% vs\. last year\.$/, (m) => `Omsætningen er ${m[1] === 'up' ? 'steget' : 'faldet'} ${m[2]}% ift. sidste år.`],
    [/^EVA handles (\d+)% of the bookkeeping; (\d+) items? still needs? a human\.$/, (m) => `EVA klarer ${m[1]}% af bogføringen; ${m[2]} ${m[2] === '1' ? 'punkt' : 'punkter'} kræver stadig et menneske.`],
    [/^Reply to (.+)$/, (m) => `Svar til ${m[1]}`],
    // ledger texts
    [/^(Bill|Invoice|Payment) — (.+)$/, (m) => `${({ Bill: 'Regning', Invoice: 'Faktura', Payment: 'Betaling' } as Record<string, string>)[m[1]]} — ${m[2]}`],
    [/^Payroll — (January|February|March|April|May|June|July|August|September|October|November|December) \(EVA payroll run\)$/, (m) => `Løn — ${({ January: 'januar', February: 'februar', March: 'marts', April: 'april', May: 'maj', June: 'juni', July: 'juli', August: 'august', September: 'september', October: 'oktober', November: 'november', December: 'december' } as Record<string, string>)[m[1]]} (EVA-lønkørsel)`],
    [/^(.+) · corrected$/, (m, tr) => `${tr(m[1])} · rettet`],
    [/^Restaurant Kødbyen · business entertainment \(Mads confirmed\)$/, () => 'Restaurant Kødbyen · repræsentation (Mads har bekræftet)'],
    [/^(Yesterday|Today|Mon|Tue|Wed|Thu|Fri|Sat|Sun) (\d\d:\d\d)$/, (m) => `${({ Yesterday: 'I går', Today: 'I dag', Mon: 'man.', Tue: 'tir.', Wed: 'ons.', Thu: 'tor.', Fri: 'fre.', Sat: 'lør.', Sun: 'søn.' } as Record<string, string>)[m[1]]} ${m[2]}`],
    [/^EVA also: (.+)$/, (m, tr) => `EVA har også: ${tr(m[1])}`],
    [/^(.+) · with scenarios$/, (m, tr) => `${tr(m[1])} · med scenarier`],
];
function fromPattern(s: string): string | undefined {
    for (const [re, fn] of PATTERNS) {
        const m = s.match(re);
        if (m) return fn(m, (x) => DA[x] ?? fromPattern(x) ?? x);
    }
    return undefined;
}

